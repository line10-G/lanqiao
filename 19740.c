/*
问题描述
小蓝，一位热爱阅读的青年，常常沉浸在书的世界里。
这天在他逛书店的时候，发现书店里的每一类书籍都有一定的库存数量，
而且部分书籍还被贴上了特别的标签。这些标签往往是一些负面评价，比
如“印刷存在错误”或者“页码混乱”等等。
小蓝仔细观察了每个书架，并记录下了每类书籍的库存总数以及被贴特别
标签的数量。现在，他需要你的帮助来分析这些数据，找出哪一类书籍被
贴上特别标签的比例最低，即从该类书籍中随机选择一本时，拿到带有特
别标签书籍的概率最小。

输入格式
输入的第一行包含一个整数 N （1≤N≤10^5），表示书籍的类别数量。

接下来的 N 行，每行包含两个整数 ti 和 pi（1≤ pi ≤ ti ≤100），
分别表示第 i 类书籍的库存总数和被贴特别标签的数量。

输出格式
输出一个整数，表示被贴特别标签比例最低的书籍类别的索引（索引从 1
开始）。如果有多个答案，则输出索引值最小的那个。
*/

#include <stdio.h>

int main(void){
    int N;
    scanf("%d",&N);
    int res = 1;
    double rat = 1.0;
    for(int i=0;i<N;++i){
        int t,p;
        scanf("%d %d",&t,&p);
        if( (double)p/t < rat){
            rat = (double)p/t;
            res = i+1;
        }
    }
    printf("%d",res);

    return 0;
}

