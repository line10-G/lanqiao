/*
小蓝一觉醒来，小蓝被困在一座高耸的塔中。这座塔共有 2025 层，
每一层都刻有一个数字的立方值，从底层的 1^3、2^3、3^3、⋯，
一直到顶层的 2025^3，层层叠叠，直入云霄。塔顶有一扇门，门旁
刻着一行字：“若想离开此塔，需找出这些立方数中个位数字为 3 的
数的个数。”

小蓝非常着急，因为他需要尽快离开这座塔，去参加即将到来的蓝桥
杯比赛。时间紧迫，请你帮助他解答这个问题。
*/
#include <stdio.h>

int main(void){
    int res=0,i;
    for(i=1;i<2026;i++){
        if((i*i*i)%10==3){
            res++;
        }
    }
    printf("%d",res);

    return 0;
}