/*
问题描述
“懒羊羊”字符串是一种特定类型的字符串，它由三个字符组成，具有以下
特点：
1.字符串长度为 3。
2.包含两种不同的字母。
3.第二个字符和第三个字符相同。
换句话说，“懒羊羊”字符串的形式应为 ABB，其中 A 和 B 是不同的字
母。
现在，给定 n 个字符串 s1​,s2,…,sn，每个字符串均由三个大写字母组
成。请你统计其中有多少个字符串符合“懒羊羊”字符串的定义。

输入格式
第一行输入一个整数 n（1≤n≤200），表示字符串的数量。
接下来的 n 行，每行输入一个由三个大写字母组成的字符串。

输出格式
输出一个整数，表示符合“懒羊羊”字符串定义的字符串总数。
*/

#include <stdio.h>

int pd(char s[]){
    if((s[0]!=s[1]) && (s[1]==s[2])){
        return 1;
    }
    return 0;
}

int main(void){
    int n;
    scanf("%d",&n);
    int res = 0;
    for(int i=0;i<n;i++){
        char s[4];
        scanf("%s",s);
        if(pd(s)){
            res++;
        }
    }
    printf("%d",res);

    return 0;
}

