#include <stdio.h>

int cntF[1000001] = {0};
int cntB[1000001] = {0};

int main(void) {
    int n;
    scanf("%d", &n);

    for (int i = 0; i < n; i++) {
        int s;
        char p[8];
        scanf("%d %s", &s, p);
        if (p[0] == 'F') cntF[s]++;
        else             cntB[s]++;
    }

    int res = 0;
    for (int i = 1; i <= 1000000; i++) {
        res += cntF[i] < cntB[i] ? cntF[i] : cntB[i];
    }
    printf("%d\n", res);
    return 0;
}

