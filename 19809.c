/*
问题描述
给定一个长度为 10 的字符串 S，它包含 10 个小写英文字母，依次
对应数字 0 到 9。
举个例子，S 为 abcdefghij，其中：
a 对应数字 0
b 对应数字 1
c 对应数字 2
…
j 对应数字 9
现在，给定另一个字符串 T，它由数字和小写英文字母组成。 你的任务
是将字符串 T 中的所有数字，按照 S 中定义的对应关系，替换为字母，
并输出替换后的字符串。

输入格式
输入包含两行：
第一行包含一个长度为 10 的字符串 S，由 10 个小写英文字母组成，
表示数字 0 到 9 的对应关系。
第二行包含一个字符串 T，由数字和小写英文字母组成，长度不超过
1000。

输出格式
输出一个字符串，即按照 S 中定义的对应关系将 T 中的数字替换为字
母后的结果。
*/

#include <stdio.h>
#include <string.h>

int main(void){
    char key[11];
    scanf("%s",key);
    char s[1001];
    scanf("%s",s);

    int len = strlen(s);
    for(int i=0;i<len;i++){
        if(s[i]>='0'&& s[i]<='9'){
            printf("%c",key[s[i]-'0']);
        }else{
            printf("%c",s[i]);
        }
    }
    printf("\n");

    return 0;
}

