/*
问题描述
新生报到当天，宿管老师需要在宿舍楼门口核对新生信息。为了避免遗漏，
他准备提前把所有新生的姓名依次写入签到表中，每名新生占用签到表中
的一行。
一张签到表最多有 K 行，可以登记至多 K 名新生。如果填写完若干张签
到表后，仍有不足 K 名新生没有登记，也需要另外使用一张签到表。
现已知共有 N 名新生需要登记，请你帮助宿管老师计算，至少需要准备多
少张签到表。

输入格式
输入一行，包含两个整数 N,K（1≤N,K≤10^9），分别表示需要登记的新
生人数和每张签到表最多能够登记的人数。

输出格式
输出一个整数，表示至少需要准备的签到表数量。
*/

#include <stdio.h>

int main(void){
    int n,k;
    scanf("%d %d",&n,&k);
    if(n%k==0){
        printf("%d\n",n/k);
    }else{
        printf("%d\n",n/k+1);
    }

    return 0;
}