/*
小蓝特别喜欢蓝色。最近，小蓝学习了颜色在计算机中的一种表示方法：
用三个 0 至 255 之间的整数（包含 0 和 255）分别表示颜色的红、
绿、蓝三个分量。

在这种颜色的表示方法下，小蓝定义了一种颜色是偏蓝的，是指蓝色分
量大于红色分量，且蓝色分量大于绿色分量。例如，红、绿、蓝分别为
10、10、11 时是偏蓝的；红、绿、蓝分别为 100、200、200 时不是
偏蓝的。

小蓝想知道，有多少种不同的颜色是偏蓝的。两种颜色如果在红、绿、
蓝中至少有一个分量值不同，就认为是不同的。
*/
#include <stdio.h>

int main(void){
    int res=0,i;
    for(i=1;i<256;i++){
        res+=i*i;
    }
    printf("%d",res);

    return 0;
}